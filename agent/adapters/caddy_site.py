"""caddy-site 适配器（C3/C3.1）：站点管理 + Caddy 服务管理。

只包含“Caddy 自己的知识”；plan/apply/备份/原子写/回滚/幂等/锁/端口登记由内核负责。

## 站点配置（``config.sites[]``，向后兼容）

- 基础：``name`` / ``kind``（``proxy`` 默认 / ``static`` / ``redirect``）/ ``domains[]``
  （优先）与旧字段 ``domain`` / ``listenPort``（默认 443）/ ``enabled``。
- 反代（``kind=proxy``）：``upstreams[]``（旧字段 ``upstream`` 兼容）、``lbPolicy``
  （round_robin/random/least_conn/ip_hash）、``healthUri``、``pathRoutes[{path, upstreams[]}]``。
- 静态（``kind=static``）：``root`` + ``file_server``，``browse`` / ``spa`` /
  ``index``（默认 index.html）/ ``tryFiles[]``。
- 跳转（``kind=redirect``）：``redirectTo``（支持 ``{uri}`` 等占位符）+ ``redirectCode``
  （301/302/307/308）。
- TLS：``tls.mode`` = ``auto``（Caddy 自动 HTTPS）/ ``manual``（Worker 解析后的
  ``tls.cert={domains,certPem,keyPem}``，写到 ``<caddy_dir 父目录>/khc-certs/<domain>.crt|.key``，
  0600）/ ``internal``（``tls internal``）/ ``off``（``http://domain:port``）；
  ``forceTls13`` 与 manual/internal 合并成单个 ``tls`` 指令（Caddy 2.8 语法）。
- 认证与安全：``basicauth``（只接受 bcrypt ``$2a$/$2b$/$2y$``）、``headers``、
  ``hsts``、``securityHeaders``、``compression``、``maxBodyBytes``（``request_body max_size``）、
  ``allowedIps``/``deniedIps``（``remote_ip`` matcher + ``handle`` 内 ``abort``）。
- 日志：``log={enabled, path}`` -> ``log { output file <path> }``；目录由适配器在 apply 前
  以 0750 创建（已存在的目录不改权限）。
- 观测入口：``liveGateway=true`` 时站点内加 ``handle /_live/* { reverse_proxy 127.0.0.1:8899 }``，
  主路由放进 ``handle { }`` 保证 fallback；不额外占端口。
- 渲染：返回 ``CaddySnippet``（内核写到 ``<caddy_dir>/caddy-site.caddy``，并保证主 Caddyfile
  有且只有一行 ``import khc.d/*``）。旧配置（domain/upstream/auto|manual|off）渲染结果
  与 v1.0 完全一致。

## 门禁 / 生效

- ``validate``：在临时镜像目录里合并「当前主 Caddyfile + 现有 khc.d imports + 本次新片段」后
  执行 ``caddy validate``（同时先把日志目录建好）；失败抛 ``ValidationFailed``，此时内核还没
  替换任何文件（旧配置保持不变、不 reload）。
- ``after_apply``：内核在片段/Caddyfile 变化时已经 validate + reload；本钩子只在「片段没变、
  只有证书内容变了」时自己 ``caddy reload``（失败回退 ``systemctl reload caddy.service``，
  仍失败抛错让内核回滚）；顺带确保日志目录存在。

## status（/state；绝不抛异常）

``unit`` / ``active`` / ``installed`` / ``version`` / ``sites``（启用站点数）/
``snippets``（托管片段文件名）/ ``validate{ok,rc,message}`` / ``lastReloadAt`` /
``lastReloadOk`` / ``lastReloadSource`` / ``lastError`` / ``siteHealth[]``。
``siteHealth`` 对已生效配置里的 enabled 站点用 HEAD/GET 探测（3s 超时，总预算 8s）：
``ok`` / ``warn``（4xx、TLS 证书校验失败=自签/internal）/ ``down`` / ``unknown``。

## 动作

``hash_password``（bcrypt，密码走 stdin）、``caddy_service``、``caddy_validate``、
``caddy_reload``（write：validate -> reload，失败不改文件）、``caddy_config``（导出主
Caddyfile + 托管片段）。

## 端口

内核 ``port_claims(config)`` 钩子：enabled 站点按 ``tcp/<listenPort>`` 登记/冲突检查
（liveGateway 不额外占端口）；声明带 ``release=True``，apply 后由内核自动放行主机
iptables 入站（站点端口无需手工规则）。render 里另外读 ``ports.json`` 做 plan 阶段的
提前冲突提示。

测试：``agent/tests/test_caddy_site.py``；所有外部命令走 ``ctx.run``（mock 注入），
不联网、不 root（健康探测在测试里被 mock）。

已知限制：
- 静态站 ``root`` 只做路径注入校验，不检查目录是否存在/可读（部署时挂载由运维保证）。
- 日志文件由 Caddy 进程创建；目录按 0750 创建但**不 chown**，Caddy 若以非 root 用户运行需
  运维确认目录属主。
- 站点删除 / TLS 改成 auto|off 后 ``khc-certs`` 里旧的 ``.crt/.key`` 不会自动清理
  （render 不能删文件；删除会破坏内核回滚语义），``uninstall`` 会清理这些文件。
- plan 的 diff 由内核生成，会包含证书/私钥文件内容（wireguard 的 .conf 同理）；Worker 转发
  面板前会脱敏 ``changes[].diff``（apps/api/src/lib/redact.ts），直连 Agent 的调用方需自行防护。
"""

