BLOCK_ALLOWED_DIRECTIVES = frozenset(
    {"reverse_proxy", "file_server", "root", "redir", "tls", "encode", "header", "log"}
)
BLOCK_TO_RE = re.compile(r"(?m)^[ \t]*to[ \t]+(.+?)[ \t]*$")
BLOCK_LB_RE = re.compile(r"(?m)^[ \t]*lb_policy[ \t]+([a-z_]+)[ \t]*$")
BLOCK_HEALTH_RE = re.compile(r"(?m)^[ \t]*health_uri[ \t]+(\S+)[ \t]*$")
BACKUP_NAME_RE = re.compile(r"\.khc-backup-[0-9]{8}T[0-9]{6}Z(?:-[0-9]+)?\.bak$")
BACKUP_KEEP = 10


def _scan_caddyfile_line(line: str, quote: Optional[str]) -> tuple[int, Optional[str], str]:
    """去掉行内注释并统计花括号净增量；引号内的 ``#``/``{``/``}`` 不参与。"""

    code_chars: list[str] = []
    index = 0
    while index < len(line):
        char = line[index]
        if quote is not None:
            if char == quote:
                quote = None
            code_chars.append(char)
        elif char in ('"', "`"):
            quote = char
            code_chars.append(char)
        elif char == "#":
            break
        else:
            code_chars.append(char)
        index += 1
    code = "".join(code_chars)
    delta = 0
    inner_quote: Optional[str] = None
    for char in code:
        if inner_quote is not None:
            if char == inner_quote:
                inner_quote = None
            continue
        if char in ('"', "`"):
            inner_quote = char
        elif char == "{":
            delta += 1
        elif char == "}":
            delta -= 1
    return delta, quote, code


def parse_caddyfile(text: str) -> dict[str, Any]:
    """按顶层结构切分 Caddyfile：站点块 / 全局 options / snippet / import。

    只做块级切分，不解释块内语义；块内语义交给 :func:`classify_site_block`。
    """

    lines = text.splitlines()
    blocks: list[dict[str, Any]] = []
    imports: list[str] = []
    depth = 0
    quote: Optional[str] = None
    start: Optional[int] = None
    opened = False
    header_parts: list[str] = []

    for index, raw in enumerate(lines):
        delta, quote, code = _scan_caddyfile_line(raw, quote)
        stripped = code.strip()
        if depth == 0 and start is None and stripped:
            start = index
            opened = False
            header_parts = []
        new_depth = depth + delta
        if start is not None:
            if not opened:
                brace = code.find("{")
                header_parts.append(code[:brace] if brace >= 0 else code)
            if delta > 0:
                opened = True
            complete = False
            if new_depth <= 0:
                if opened:
                    complete = True
                elif not code.rstrip().endswith(","):
                    # 顶层普通语句（如 import）；以逗号结尾视为跨行站点地址
                    complete = True
            if complete:
                header = " ".join(part.strip() for part in header_parts if part.strip())
                header = " ".join(header.split())
                block_text = "\n".join(lines[start : index + 1])
                kind = "site"
                if not header:
                    kind = "options"
                elif header.startswith("("):
                    kind = "snippet"
                elif header.split(" ")[0] == "import":
                    kind = "import"
                    target = header[len("import") :].strip()
                    if target and not target.startswith("khc.d/"):
                        imports.append(target)
                blocks.append(
                    {
                        "kind": kind,
                        "header": header,
                        "startLine": start + 1,
                        "endLine": index + 1,
                        "text": block_text,
                        "hash": hashlib.sha256(block_text.encode("utf-8")).hexdigest(),
                    }
                )
                start = None
        depth = max(new_depth, 0)

    if start is not None:
        block_text = "\n".join(lines[start:])
        blocks.append(
            {
                "kind": "invalid",
                "header": "",
                "startLine": start + 1,
                "endLine": len(lines),
                "text": block_text,
                "hash": hashlib.sha256(block_text.encode("utf-8")).hexdigest(),
                "reason": "花括号未闭合",
            }
        )
    return {"blocks": blocks, "imports": imports}


def _block_directives(inner: str) -> list[tuple[str, str]]:
    """收集站点块内第一层指令（跳过嵌套块内部）。"""

    directives: list[tuple[str, str]] = []
    depth = 0
    quote: Optional[str] = None
    for raw in inner.splitlines():
        delta, quote, code = _scan_caddyfile_line(raw, quote)
        stripped = code.strip()
        if depth == 0 and stripped:
            directives.append((stripped.split()[0], stripped))
        depth = max(depth + delta, 0)
    return directives


def _parse_block_addresses(header: str) -> tuple[list[str], Optional[int], Optional[str]]:
    """解析站点块地址行，返回 (域名列表, 监听端口, 无法接管的说明)。"""

    tokens = [token for token in re.split(r"[\s,]+", header.strip()) if token]
    domains: list[str] = []
    listen_port: Optional[int] = None
    scheme: Optional[str] = None
    for token in tokens:
        value = token
        if value.lower().startswith("http://"):
            scheme = "http"
            value = value[len("http://") :]
        elif value.lower().startswith("https://"):
            scheme = "https"
            value = value[len("https://") :]
        if not value:
            continue
        if value.startswith("["):
            return [], None, "IPv6 地址暂不支持自动接管"
        if value.startswith(":"):
            port_text = value[1:]
            if not port_text.isdigit():
                return [], None, f"无法识别地址：{token}"
            listen_port = int(port_text)
            continue
        if "/" in value:
            return [], None, f"地址包含路径匹配，暂不支持：{token}"
        if "*" in value:
            return [], None, f"通配符域名暂不支持自动接管：{token}"
        host = value
        if ":" in value:
            host, port_text = value.rsplit(":", 1)
            if not port_text.isdigit():
                return [], None, f"无法识别端口：{token}"
            listen_port = int(port_text)
        try:
            domain = normalize_domain(host)
        except BadRequest:
            return [], None, f"无法识别域名：{token}"
        if domain not in domains:
            domains.append(domain)
    if listen_port is None:
        listen_port = 80 if scheme == "http" else 443
    if not domains:
        return [], None, "未指定域名（仅端口或空地址），暂不支持自动接管"
    return domains, listen_port, None


def _classify_log(inner: str, log_lines: list[str]) -> tuple[bool, str, Optional[str]]:
    """把 ``log`` 指令映射为面板日志设置；无法无损映射时返回阻断原因。

    面板托管模型只支持 ``log { output file <绝对路径> }``；裸 ``log``、多条 ``log``、
    ``output stdout`` 等形态会改变运行语义，一律阻断而不是猜着转换。
    """

    if not log_lines:
        return False, "", None
    if len(log_lines) > 1:
        return False, "", "存在多条 log 指令，暂不支持自动接管"
    line = log_lines[0]
    if "{" not in line:
        return False, "", "log 指令未指定文件输出（面板托管需要 log { output file <path> }）"
    match = re.search(r"(?ms)^[ \t]*log[ \t]*\{(.*?)^[ \t]*\}", inner)
    body_text = match.group(1) if match else line.split("{", 1)[1].rsplit("}", 1)[0]
    body = [item.strip() for item in body_text.splitlines() if item.strip()]
    if len(body) != 1 or not body[0].startswith("output file "):
        return False, "", "log 块形式暂不支持自动接管（只能识别 output file <path>）"
    try:
        return True, normalize_log_path(body[0][len("output file ") :].strip()), None
    except BadRequest:
        return False, "", "log 输出路径无法识别，暂不支持自动接管"


