def _text(value: Any) -> str:
    """转成去掉首尾空白的字符串（None/bool 视为空）。"""

    if value is None or isinstance(value, bool):
        return ""
    return str(value).strip()


def _listening_inodes(proc_root: str) -> dict[int, list[str]]:
    """只读 ``<proc_root>/net/tcp{,6}``：返回监听端口 -> socket inode。"""

    result: dict[int, list[str]] = {}
    for name in ("tcp", "tcp6"):
        path = os.path.join(proc_root, "net", name)
        try:
            with open(path, "r", encoding="utf-8") as handle:
                lines = handle.readlines()[1:]
        except OSError:
            continue
        for line in lines:
            fields = line.split()
            if len(fields) < 10 or fields[3] != "0A":
                continue
            try:
                port = int(fields[1].rsplit(":", 1)[1], 16)
            except (IndexError, ValueError):
                continue
            result.setdefault(port, []).append(fields[9])
    return result


def _inode_owner_command(proc_root: str, inodes: set[str]) -> str:
    """按 socket inode 反查进程命令行（读不到时返回空串）。"""

    wanted = {f"socket:[{inode}]" for inode in inodes}
    try:
        pids = [name for name in os.listdir(proc_root) if name.isdigit()]
    except OSError:
        return ""
    for pid in pids:
        fd_dir = os.path.join(proc_root, pid, "fd")
        try:
            fds = os.listdir(fd_dir)
        except OSError:
            continue
        for fd in fds:
            try:
                target = os.readlink(os.path.join(fd_dir, fd))
            except OSError:
                continue
            if target not in wanted:
                continue
            try:
                with open(os.path.join(proc_root, pid, "cmdline"), "rb") as handle:
                    return handle.read().decode("utf-8", "replace").replace("\x00", " ").strip()
            except OSError:
                return ""
    return ""


def _single_line(value: Any, field: str) -> str:
    text = _text(value)
    if any(char in text for char in _FORBIDDEN_TEXT_CHARS):
        raise ValidationFailed(f"{field} 不允许包含换行或 NUL 字符", details={"field": field})
    return text


def normalize_domain(value: Any, *, field: str = "domain") -> str:
    """校验并归一化站点域名（不带端口、不带通配符，统一小写）。"""

    raw = _single_line(value, field).lower()
    if not raw:
        raise ValidationFailed("站点 domain 不能为空", details={"field": field})
    if "/" in raw or ":" in raw:
        raise ValidationFailed(
            "站点 domain 只能是主机名（不带协议/端口；端口用 listenPort 单独配置）",
            details={"field": field},
        )
    if raw.endswith("."):
        raw = raw[:-1]
    if not raw or len(raw) > 253:
        raise ValidationFailed("站点 domain 长度非法（1-253 个字符）", details={"field": field})
    for label in raw.split("."):
        if not DOMAIN_LABEL_RE.match(label):
            raise ValidationFailed(
                "站点 domain 不是合法主机名（只允许字母/数字/连字符，标签不能以连字符开头或结尾）",
                details={"field": field, "domain": raw},
            )
    return raw


def normalize_cert_domain(value: Any, *, field: str = "tls.cert.domains") -> str:
    """校验证书域名（允许单层通配 ``*.example.com``，统一小写）。"""

    raw = _single_line(value, field).lower()
    if not raw:
        raise ValidationFailed("证书域名不能为空", details={"field": field})
    wildcard = raw.startswith("*.")
    if wildcard:
        raw = raw[2:]
    if "/" in raw or ":" in raw:
        raise ValidationFailed("证书域名只能是域名（不带端口/协议）", details={"field": field})
    if raw.endswith("."):
        raw = raw[:-1]
    if not raw or len(raw) > 253:
        raise ValidationFailed("证书域名长度非法（1-253 个字符）", details={"field": field})
    for label in raw.split("."):
        if not DOMAIN_LABEL_RE.match(label):
            raise ValidationFailed("证书域名不是合法主机名", details={"field": field})
    return f"*.{raw}" if wildcard else raw


def normalize_upstream(value: Any) -> str:
    """校验 reverse_proxy 上游：``host:port`` / ``scheme://host:port`` / ``unix//path``。"""

    text = _single_line(value, "upstream")
    if not text:
        raise ValidationFailed(
            "站点 upstream 不能为空（reverse_proxy 目标，例如 10.99.0.2:8080）",
            details={"field": "upstream"},
        )
    if len(text) > 255:
        raise ValidationFailed("站点 upstream 太长（>255）", details={"field": "upstream"})
    if any(char.isspace() for char in text):
        raise ValidationFailed("站点 upstream 不允许包含空白字符", details={"field": "upstream"})
    if any(char in text for char in '{}"\\#'):
        raise ValidationFailed(
            "站点 upstream 不允许包含花括号/引号/反斜杠/# 等 Caddyfile 特殊字符",
            details={"field": "upstream"},
        )
    if text.startswith("unix/"):
        return text
    candidate = text
    match = UPSTREAM_SCHEME_RE.match(candidate)
    if match:
        candidate = candidate[match.end():]
    hostport = UPSTREAM_HOSTPORT_RE.match(candidate)
    if hostport is None:
        raise ValidationFailed(
            "站点 upstream 格式非法（需要 host:port，例如 10.99.0.2:8080 或 http://svc:8080）",
            details={"field": "upstream"},
        )
    port = int(hostport.group(1))
    if not 1 <= port <= 65535:
        raise ValidationFailed("站点 upstream 端口超出范围（1-65535）", details={"field": "upstream"})
    return text


def normalize_header(name: Any, value: Any) -> tuple[str, str]:
    """校验 Header 名/值，返回用于渲染的 (name, value)。"""

    header_name = _single_line(name, "headers")
    if not HEADER_NAME_RE.match(header_name):
        raise ValidationFailed(
            "Header 名非法（只允许 HTTP token 字符）",
            details={"field": "headers", "header": header_name[:80]},
        )
    if not isinstance(value, str):
        raise ValidationFailed(
            "Header 值必须是字符串",
            details={"field": "headers", "header": header_name},
        )
    header_value = value.strip()
    if not header_value:
        raise ValidationFailed(
            "Header 值不能为空",
            details={"field": "headers", "header": header_name},
        )
    if len(header_value) > 1024:
        raise ValidationFailed(
            "Header 值太长（>1024）",
            details={"field": "headers", "header": header_name},
        )
    for char in header_value:
        if char in ("\x00", "\r", "\n", "{", "}", '"', "\\") or ord(char) < 0x20 or ord(char) == 0x7F:
            raise ValidationFailed(
                "Header 值包含非法字符（不允许换行/花括号/引号/反斜杠/控制字符）",
                details={"field": "headers", "header": header_name},
            )
    return header_name, header_value


def normalize_bcrypt_hash(value: Any) -> str:
    """只接受 bcrypt 哈希（$2a$/$2b$/$2y$）。"""

    text = _single_line(value, "basicauth.passwordHash")
    if not text:
        raise ValidationFailed(
            "BasicAuth 缺少 passwordHash（先用 hash_password 动作生成 bcrypt 哈希）",
            details={"field": "basicauth.passwordHash"},
        )
    if not BCRYPT_RE.match(text):
        raise ValidationFailed(
            "BasicAuth 只接受 bcrypt 哈希（$2a$/$2b$/$2y$ 开头的 60 字符），不接受明文或其他算法",
            details={"field": "basicauth.passwordHash"},
        )
    return text


def _pem_text(value: Any) -> str:
    """PEM 内容允许换行；只去首尾空白并拒绝 NUL。"""

    if value is None or isinstance(value, bool):
        return ""
    text = str(value).strip()
    if "\x00" in text:
        raise ValidationFailed("证书材料不允许包含 NUL 字符", details={"field": "tls.cert"})
    return text


def _normalize_cert_pem(value: Any, field: str) -> str:
    text = _pem_text(value)
    if not text:
        raise ValidationFailed("证书材料缺少 PEM 内容", details={"field": field})
    if _CERT_BEGIN not in text or _CERT_END not in text:
        raise ValidationFailed(
            "证书不是合法 PEM（缺少 BEGIN/END CERTIFICATE）",
            details={"field": field},
        )
    return text if text.endswith("\n") else text + "\n"


def _normalize_key_pem(value: Any, field: str) -> str:
    text = _pem_text(value)
    if not text:
        raise ValidationFailed("证书材料缺少私钥 PEM 内容", details={"field": field})
    for marker in _KEY_MARKERS:
        begin = f"-----BEGIN {marker}-----"
        end = f"-----END {marker}-----"
        # 加密私钥是 BEGIN ENCRYPTED PRIVATE KEY，不匹配任何 END 标记。
        if begin in text and end in text:
            return text if text.endswith("\n") else text + "\n"
    raise ValidationFailed(
        "私钥不是合法 PEM（缺少 BEGIN/END PRIVATE KEY；不支持加密私钥）",
        details={"field": field},
    )


def cert_covers_domain(domain: str, domains: Any) -> bool:
    """证书域名列表是否覆盖站点域名（支持单层通配 ``*.example.com``）。"""

    if not isinstance(domains, (list, tuple)):
        return False
    for raw in domains:
        candidate = _text(raw).lower()
        if candidate.endswith("."):
            candidate = candidate[:-1]
        if not candidate:
            continue
        if candidate == domain:
            return True
        if candidate.startswith("*."):
            suffix = candidate[1:]  # ".example.com"
            if domain.endswith(suffix) and domain.count(".") == suffix.count("."):
                return True
    return False


def count_site_blocks(snippet: Optional[str]) -> int:
    """统计片段里的顶层站点块数量（站点块行不带缩进、以 ``{`` 结尾）。"""

    count = 0
    for line in (snippet or "").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or line[:1].isspace():
            continue
        if stripped.endswith("{"):
            count += 1
    return count


def normalize_root(value: Any, *, field: str = "root") -> str:
    """静态站根目录：绝对路径、无注入、无 ``..``。"""

    text = _single_line(value, field)
    if not text:
        raise ValidationFailed(
            "静态站点必须配置 root（文件根目录，例如 /var/www/blog）",
            details={"field": field},
        )
    if len(text) > 512:
        raise ValidationFailed("root 路径太长（>512）", details={"field": field})
    if not ROOT_SAFE_RE.match(text):
        raise ValidationFailed(
            "root 必须是绝对路径，且不允许空白/花括号/引号/反斜杠/控制字符",
            details={"field": field},
        )
    if ".." in text.split("/"):
        raise ValidationFailed("root 不允许包含 ..", details={"field": field})
    if text == "/":
        raise ValidationFailed("root 不允许是文件系统根目录 /", details={"field": field})
    return text.rstrip("/") or "/"


def normalize_redirect_target(value: Any, *, field: str = "redirectTo") -> str:
    """跳转目标：http(s) URL 或以 / 开头的路径；允许 ``{uri}`` 等占位符。"""

    text = _single_line(value, field)
    if not text:
        raise ValidationFailed(
            "跳转站点必须配置 redirectTo（例如 https://example.com{uri}）",
            details={"field": field},
        )
    if len(text) > 2048:
        raise ValidationFailed("redirectTo 太长（>2048）", details={"field": field})
    if any(char.isspace() for char in text):
        raise ValidationFailed("redirectTo 不允许包含空白字符", details={"field": field})
    if any(char in text for char in ('"', "'", "\\", "#")):
        raise ValidationFailed("redirectTo 不允许包含引号/反斜杠/#", details={"field": field})
    remainder = PLACEHOLDER_RE.sub("", text)
    if "{" in remainder or "}" in remainder:
        raise ValidationFailed(
            "redirectTo 里的占位符格式非法（只允许 {uri}/{host}/{path}/{query} 等 {name} 形式）",
            details={"field": field},
        )
    lowered = text.lower()
    if not (lowered.startswith("http://") or lowered.startswith("https://") or text.startswith("/")):
        raise ValidationFailed(
            "redirectTo 必须是 http(s):// 开头的 URL 或以 / 开头的路径",
            details={"field": field},
        )
    return text


def normalize_ip_rules(values: Any, *, field: str) -> list[str]:
    """IP/CIDR 列表（remote_ip matcher），规范化后去重。"""

    if values is None:
        return []
    if not isinstance(values, (list, tuple)):
        raise ValidationFailed(f"{field} 必须是数组", details={"field": field})
    rules: list[str] = []
    for item in values:
        text = _single_line(item, field)
        if not text:
            continue
        try:
            network = ipaddress.ip_network(text, strict=False)
        except ValueError as exc:
            raise ValidationFailed(
                f"{field} 含非法 IP/CIDR: {text!r}（{exc}）",
                details={"field": field},
            ) from None
        canonical = str(network)
        if canonical not in rules:
            rules.append(canonical)
    return rules


def normalize_log_path(value: Any, *, field: str = "log.path") -> str:
    text = _single_line(value, field)
    if not text:
        raise ValidationFailed(
            "启用日志时 log.path 不能为空（绝对路径，例如 /var/log/caddy/blog.log）",
            details={"field": field},
        )
    if len(text) > 512:
        raise ValidationFailed("log.path 太长（>512）", details={"field": field})
    if not LOG_SAFE_RE.match(text):
        raise ValidationFailed(
            "log.path 必须是绝对路径，且不允许空白/#/花括号/引号/反斜杠/控制字符",
            details={"field": field},
        )
    if ".." in text.split("/"):
        raise ValidationFailed("log.path 不允许包含 ..", details={"field": field})
    if text.endswith("/"):
        raise ValidationFailed("log.path 必须是文件路径，不能以 / 结尾", details={"field": field})
    return text


def normalize_health_uri(value: Any, *, field: str = "healthUri") -> str:
    text = _single_line(value, field)
    if not text:
        return ""
    if len(text) > 256:
        raise ValidationFailed("healthUri 太长（>256）", details={"field": field})
    if not HEALTH_URI_SAFE_RE.match(text):
        raise ValidationFailed(
            "healthUri 必须是以 / 开头的 URI（可带 query），不允许空白/花括号/引号",
            details={"field": field},
        )
    return text


def normalize_index(value: Any, *, field: str = "index") -> str:
    text = _single_line(value, field) or DEFAULT_INDEX
    if not INDEX_RE.match(text) or text in (".", ".."):
        raise ValidationFailed(
            "index 只能是文件名（字母/数字/._-，1-64 字符）",
            details={"field": field},
        )
    return text


def normalize_path_route_path(value: Any, *, field: str = "pathRoutes.path") -> str:
    text = _single_line(value, field)
    if not text:
        raise ValidationFailed("pathRoutes.path 不能为空（例如 /api/*）", details={"field": field})
    if len(text) > 255:
        raise ValidationFailed("pathRoutes.path 太长（>255）", details={"field": field})
    if not PATH_ROUTE_SAFE_RE.match(text):
        raise ValidationFailed(
            "pathRoutes.path 必须是以 / 开头的匹配路径（不允许空白/花括号/引号/反斜杠）",
            details={"field": field},
        )
    return text


def normalize_try_files(values: Any, *, field: str = "tryFiles") -> list[str]:
    if values is None:
        return []
    if not isinstance(values, (list, tuple)):
        raise ValidationFailed(f"{field} 必须是数组", details={"field": field})
    tokens: list[str] = []
    for item in values:
        token = _single_line(item, field)
        if not token:
            continue
        if len(token) > 255:
            raise ValidationFailed("tryFiles 单项太长（>255）", details={"field": field})
        remainder = PLACEHOLDER_RE.sub("", token)
        if "{" in remainder or "}" in remainder:
            raise ValidationFailed(
                "tryFiles 里的占位符格式非法（只允许 {path} 这类 {name} 形式）",
                details={"field": field},
            )
        if any(char in token for char in ('"', "'", "\\")) or any(ord(char) < 0x20 for char in token):
            raise ValidationFailed("tryFiles 不允许引号/反斜杠/控制字符", details={"field": field})
        if any(char.isspace() for char in token):
            raise ValidationFailed("tryFiles 单项不允许空白（多项用数组）", details={"field": field})
        tokens.append(token)
    return tokens


def _with_import(text: Optional[str]) -> str:
    """与内核保持一致：保证主 Caddyfile 里有且只有一行 ``import khc.d/*``。"""

    if text is None or not text.strip():
        return "# khc-agent managed Caddyfile\nimport khc.d/*\n"
    if IMPORT_RE.search(text):
        return text
    return text.rstrip("\n") + "\n\n# managed by khc-agent\nimport khc.d/*\n"


