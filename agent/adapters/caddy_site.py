    def _normalize_path_routes(
        self,
        raw: Any,
        index: int,
        label: str,
        *,
        live_gateway: bool,
    ) -> list[dict[str, Any]]:
        if raw is None:
            return []
        if not isinstance(raw, list):
            raise ValidationFailed(
                f"{label}.pathRoutes 必须是数组",
                details={"field": f"sites[{index}].pathRoutes"},
            )
        routes: list[dict[str, Any]] = []
        seen_paths: set[str] = set()
        for route_index, item in enumerate(raw):
            if not isinstance(item, Mapping):
                raise ValidationFailed(
                    f"{label}.pathRoutes[{route_index}] 必须是 object",
                    details={"field": f"sites[{index}].pathRoutes"},
                )
            path = normalize_path_route_path(
                item.get("path"),
                field=f"sites[{index}].pathRoutes[{route_index}].path",
            )
            if path in seen_paths:
                raise ValidationFailed(
                    f"{label}.pathRoutes 路径重复: {path}",
                    details={"field": f"sites[{index}].pathRoutes"},
                )
            if live_gateway and path == LIVE_GATEWAY_PATH:
                raise ValidationFailed(
                    f"{label}.pathRoutes 与 liveGateway 的 {LIVE_GATEWAY_PATH} 冲突",
                    details={"field": f"sites[{index}].pathRoutes"},
                )
            seen_paths.add(path)
            route_upstreams: list[str] = []
            raw_upstreams = item.get("upstreams")
            if isinstance(raw_upstreams, list):
                for upstream_item in raw_upstreams:
                    upstream = normalize_upstream(upstream_item)
                    if upstream not in route_upstreams:
                        route_upstreams.append(upstream)
            if not route_upstreams:
                raise ValidationFailed(
                    f"{label}.pathRoutes[{route_index}] 缺少 upstreams",
                    details={"field": f"sites[{index}].pathRoutes[{route_index}].upstreams"},
                )
            routes.append({"path": path, "upstreams": route_upstreams})
        if len(routes) > MAX_PATH_ROUTES:
            raise ValidationFailed(
                f"{label}.pathRoutes 过多（>{MAX_PATH_ROUTES}）",
                details={"field": f"sites[{index}].pathRoutes"},
            )
        return routes

    def _normalize_sites(self, config: Mapping[str, Any]) -> list[dict[str, Any]]:
        raw_sites = config.get("sites")
        if not isinstance(raw_sites, list):
            return []
        sites: list[dict[str, Any]] = []
        seen_addresses: dict[tuple[str, int], int] = {}
        seen_names: dict[str, int] = {}
        for index, raw in enumerate(raw_sites):
            if not isinstance(raw, Mapping):
                raise ValidationFailed(
                    f"站点配置必须是 object: sites[{index}]",
                    details={"field": f"sites[{index}]"},
                )
            if not bool(raw.get("enabled", True)):
                continue
            label = self._site_label(index, raw)
            kind = _text(raw.get("kind")) or "proxy"
            if kind not in KINDS:
                raise ValidationFailed(
                    f"{label}.kind 只能是 proxy/static/redirect",
                    details={"field": f"sites[{index}].kind"},
                )
            domains = self._normalize_domains(raw, index, label)
            primary_domain = domains[0]
            port = raw.get("listenPort", DEFAULT_LISTEN_PORT)
            if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
                raise ValidationFailed(
                    f"{label}.listenPort 必须是 1-65535 的整数",
                    details={"field": f"sites[{index}].listenPort"},
                )
            live_gateway = bool(raw.get("liveGateway", False))

            upstreams: list[str] = []
            lb_policy = DEFAULT_LB_POLICY
            health_uri = ""
            path_routes: list[dict[str, Any]] = []
            root = ""
            browse = False
            spa = False
            index_name = DEFAULT_INDEX
            try_files: list[str] = []
            redirect_to = ""
            redirect_code = DEFAULT_REDIRECT_CODE

            if kind == "proxy":
                upstreams = self._normalize_upstreams(raw, index, label)
                lb_policy = _text(raw.get("lbPolicy")) or DEFAULT_LB_POLICY
                if lb_policy not in LB_POLICIES:
                    raise ValidationFailed(
                        f"{label}.lbPolicy 只能是 {'/'.join(LB_POLICIES)}",
                        details={"field": f"sites[{index}].lbPolicy"},
                    )
                health_uri = normalize_health_uri(
                    raw.get("healthUri"),
                    field=f"sites[{index}].healthUri",
                )
                path_routes = self._normalize_path_routes(
                    raw.get("pathRoutes"),
                    index,
                    label,
                    live_gateway=live_gateway,
                )
            elif kind == "static":
                root = normalize_root(raw.get("root"), field=f"sites[{index}].root")
                browse = bool(raw.get("browse", False))
                spa = bool(raw.get("spa", False))
                index_name = normalize_index(raw.get("index"), field=f"sites[{index}].index")
                try_files = normalize_try_files(
                    raw.get("tryFiles"),
                    field=f"sites[{index}].tryFiles",
                )
            else:  # redirect
                redirect_to = normalize_redirect_target(
                    raw.get("redirectTo"),
                    field=f"sites[{index}].redirectTo",
                )
                redirect_code_value = raw.get("redirectCode", DEFAULT_REDIRECT_CODE)
                if isinstance(redirect_code_value, bool) or redirect_code_value not in REDIRECT_CODES:
                    raise ValidationFailed(
                        f"{label}.redirectCode 只能是 301/302/307/308",
                        details={"field": f"sites[{index}].redirectCode"},
                    )
                redirect_code = int(redirect_code_value)

            tls = raw.get("tls") if isinstance(raw.get("tls"), Mapping) else {}
            tls_mode = _text(tls.get("mode")) or "auto"
            if tls_mode not in TLS_MODES:
                raise ValidationFailed(
                    f"{label}.tls.mode 只能是 auto/manual/internal/off",
                    details={"field": f"sites[{index}].tls.mode"},
                )
            cert_pem = ""
            key_pem = ""
            cert_domains: list[str] = []
            if tls_mode == "manual":
                cert = tls.get("cert")
                if not isinstance(cert, Mapping):
                    raise ValidationFailed(
                        f"{label} 使用 manual TLS 时必须提供 tls.cert"
                        "（Worker 解析后的 {domains, certPem, keyPem}）",
                        details={"field": f"sites[{index}].tls.cert"},
                    )
                if "certPem" not in cert and "keyPem" not in cert and "$cert" in cert:
                    raise ValidationFailed(
                        f"{label}.tls.cert 仍是未解析的 $cert 引用；请确认 Worker 已解析证书材料",
                        details={"field": f"sites[{index}].tls.cert"},
                    )
                cert_pem = _normalize_cert_pem(cert.get("certPem"), f"sites[{index}].tls.cert.certPem")
                key_pem = _normalize_key_pem(cert.get("keyPem"), f"sites[{index}].tls.cert.keyPem")
                raw_domains = cert.get("domains")
                if not isinstance(raw_domains, list) or not raw_domains:
                    raise ValidationFailed(
                        f"{label}.tls.cert.domains 不能为空（用于校验证书是否覆盖站点域名）",
                        details={"field": f"sites[{index}].tls.cert.domains"},
                    )
                cert_domains = [
                    normalize_cert_domain(item, field=f"sites[{index}].tls.cert.domains")
                    for item in raw_domains
                ]
                for domain in domains:
                    if not cert_covers_domain(domain, cert_domains):
                        raise ValidationFailed(
                            f"{label} 的证书不包含域名 {domain}（证书域名: {', '.join(cert_domains)}）",
                            details={"field": f"sites[{index}].tls.cert.domains", "domain": domain},
                        )

            basicauth = raw.get("basicauth") if isinstance(raw.get("basicauth"), Mapping) else {}
            user = _single_line(basicauth.get("user"), f"{label}.basicauth.user")
            password_hash = _single_line(basicauth.get("passwordHash"), f"{label}.basicauth.passwordHash")
            if user and not password_hash:
                raise ValidationFailed(
                    f"{label} 配置了 BasicAuth 用户名但缺少 passwordHash（先调用 hash_password）",
                    details={"field": f"sites[{index}].basicauth.passwordHash"},
                )
            if password_hash and not user:
                raise ValidationFailed(
                    f"{label} 配置了 BasicAuth passwordHash 但缺少 user",
                    details={"field": f"sites[{index}].basicauth.user"},
                )
            if user:
                if not BASICAUTH_USER_RE.match(user):
                    raise ValidationFailed(
                        f"{label}.basicauth.user 非法（只允许字母/数字/._@-，1-64 字符）",
                        details={"field": f"sites[{index}].basicauth.user"},
                    )
                password_hash = normalize_bcrypt_hash(password_hash)

            raw_headers = raw.get("headers") if isinstance(raw.get("headers"), Mapping) else {}
            headers: dict[str, str] = {}
            for header_name, header_value in raw_headers.items():
                name, value = normalize_header(header_name, header_value)
                headers[name] = value

            allowed_ips = normalize_ip_rules(raw.get("allowedIps"), field=f"sites[{index}].allowedIps")
            denied_ips = normalize_ip_rules(raw.get("deniedIps"), field=f"sites[{index}].deniedIps")

            max_body_bytes = raw.get("maxBodyBytes")
            if max_body_bytes is None:
                max_body_bytes = 0
            if isinstance(max_body_bytes, bool) or not isinstance(max_body_bytes, int):
                raise ValidationFailed(
                    f"{label}.maxBodyBytes 必须是整数（0 表示不限制）",
                    details={"field": f"sites[{index}].maxBodyBytes"},
                )
            if not 0 <= max_body_bytes <= MAX_BODY_BYTES_LIMIT:
                raise ValidationFailed(
                    f"{label}.maxBodyBytes 超出范围（0-{MAX_BODY_BYTES_LIMIT}）",
                    details={"field": f"sites[{index}].maxBodyBytes"},
                )

            log = raw.get("log") if isinstance(raw.get("log"), Mapping) else {}
            log_enabled = bool(log.get("enabled", False))
            log_path = ""
            if log_enabled:
                log_path = normalize_log_path(log.get("path"), field=f"sites[{index}].log.path")

            force_tls13 = bool(raw.get("forceTls13", False))
            raw_name = _single_line(raw.get("name"), f"{label}.name")
            name_text = raw_name or primary_domain

            for domain in domains:
                address_key = (domain, int(port))
                if address_key in seen_addresses:
                    raise ValidationFailed(
                        f"站点地址重复: {domain}:{port}"
                        f"（sites[{seen_addresses[address_key]}] 与 sites[{index}]）",
                        details={"field": "sites", "domain": domain, "listenPort": int(port)},
                    )
                seen_addresses[address_key] = index
            # 只校验显式 name 的唯一性；未命名站点（旧配置）按 primary domain 展示，
            # 同一域名不同端口的旧配置不应因此报错。
            if raw_name:
                if raw_name in seen_names:
                    raise ValidationFailed(
                        f"站点 name 重复: {raw_name!r}（sites[{seen_names[raw_name]}] 与 sites[{index}]）",
                        details={"field": "sites", "name": raw_name},
                    )
                seen_names[raw_name] = index

            sites.append(
                {
                    "name": name_text,
                    "kind": kind,
                    "domains": domains,
                    "primaryDomain": primary_domain,
                    "listenPort": int(port),
                    "upstreams": upstreams,
                    "lbPolicy": lb_policy,
                    "healthUri": health_uri,
                    "pathRoutes": path_routes,
                    "root": root,
                    "browse": browse,
                    "spa": spa,
                    "index": index_name,
                    "tryFiles": try_files,
                    "redirectTo": redirect_to,
                    "redirectCode": redirect_code,
                    "tlsMode": tls_mode,
                    "certPem": cert_pem,
                    "keyPem": key_pem,
                    "certDomains": cert_domains,
                    "forceTls13": force_tls13,
                    "user": user,
                    "passwordHash": password_hash,
                    "headers": headers,
                    "hsts": bool(raw.get("hsts", False)),
                    "securityHeaders": bool(raw.get("securityHeaders", False)),
                    "compression": bool(raw.get("compression", False)),
                    "allowedIps": allowed_ips,
                    "deniedIps": denied_ips,
                    "maxBodyBytes": int(max_body_bytes),
                    "logEnabled": log_enabled,
                    "logPath": log_path,
                    "liveGateway": live_gateway,
                }
            )

        # 固定顺序输出（主域名 + 端口），保证配置顺序变化不会产生无意义的 diff。
        sites.sort(key=lambda item: (item["primaryDomain"], item["listenPort"]))
        return sites

    def _certificate_files(self, ctx: Ctx, sites: list[dict[str, Any]]) -> list[File]:
        """manual 模式把 PEM 落到 khc-certs/<domain>.crt|.key（0600），并按路径去重。"""

        files: dict[str, File] = {}
        for site in sites:
            if site["tlsMode"] != "manual":
                continue
            domain = site["primaryDomain"]
            pairs = (
                (self.cert_path(ctx, domain, "crt"), site["certPem"]),
                (self.cert_path(ctx, domain, "key"), site["keyPem"]),
            )
            for path, content in pairs:
                existing = files.get(path)
                if existing is not None:
                    if existing.content != content:
                        raise ValidationFailed(
                            f"同一域名 {domain} 的多个站点声明了不同证书内容，无法共用 {path}",
                            details={"field": "sites", "path": path},
                        )
                    continue
                files[path] = File(path, content, mode=0o600)
        return list(files.values())

    # ------------------------------------------------------------------
    # Caddyfile 渲染辅助
    # ------------------------------------------------------------------
    def _address(self, site: Mapping[str, Any]) -> str:
        port = site["listenPort"]
        if site["tlsMode"] == "off":
            return ", ".join(f"http://{domain}:{port}" for domain in site["domains"])
        return ", ".join(f"{domain}:{port}" for domain in site["domains"])

    def _render_block(self, site: Mapping[str, Any], certs_dir: str) -> str:
        # 顺序与 v1.0 保持一致（routing -> tls -> header -> basic_auth），旧配置升级后
        # 不会产生无意义的 diff；Caddyfile 里普通指令的顺序不影响语义（Caddy 统一排序）。
        lines = [self._address(site) + " {"]
        self._append_routing(lines, site)
        self._append_tls(lines, site, certs_dir)
        self._append_log(lines, site)
        self._append_headers(lines, site)
        self._append_body_limit(lines, site)
        self._append_compression(lines, site)
        self._append_basicauth(lines, site)
        lines.append("}")
        return "\n".join(lines)

    def _append_tls(self, lines: list[str], site: Mapping[str, Any], certs_dir: str) -> None:
        mode = site["tlsMode"]
        if mode == "off":
            return
        force = bool(site["forceTls13"])
        if mode == "manual":
            cert = os.path.join(certs_dir, f"{site['primaryDomain']}.crt")
            key = os.path.join(certs_dir, f"{site['primaryDomain']}.key")
            head = f"tls {cert} {key}"
        elif mode == "internal":
            head = "tls internal"
        else:  # auto：交给 Caddy 自动 HTTPS
            head = "tls"
        if not force:
            if head == "tls":
                return
            lines.append(f"    {head}")
            return
        if head == "tls":
            lines.append("    tls {")
        else:
            lines.append(f"    {head} {{")
        lines.append("        protocols tls1.3")
        lines.append("    }")

    def _append_headers(self, lines: list[str], site: Mapping[str, Any]) -> None:
        headers = dict(site["headers"])
        extra: dict[str, str] = {}
        if site["securityHeaders"]:
            extra.update(SECURITY_HEADERS)
        if site["hsts"] and site["tlsMode"] != "off":
            extra["Strict-Transport-Security"] = HSTS_VALUE
        existing = {name.lower() for name in headers}
        for name in sorted(extra):
            if name.lower() not in existing:
                headers[name] = extra[name]
        if not headers:
            return
        lines.append("    header {")
        for name in sorted(headers):
            lines.append(f'        {name} "{headers[name]}"')
        lines.append("    }")

    def _append_log(self, lines: list[str], site: Mapping[str, Any]) -> None:
        if not site["logEnabled"]:
            return
        lines.append("    log {")
        lines.append(f"        output file {site['logPath']}")
        lines.append("    }")

    def _append_body_limit(self, lines: list[str], site: Mapping[str, Any]) -> None:
        if int(site["maxBodyBytes"]) <= 0:
            return
        lines.append("    request_body {")
        lines.append(f"        max_size {int(site['maxBodyBytes'])}")
        lines.append("    }")

    def _append_compression(self, lines: list[str], site: Mapping[str, Any]) -> None:
        if site["compression"]:
            lines.append("    encode zstd gzip")

    def _append_basicauth(self, lines: list[str], site: Mapping[str, Any]) -> None:
        if not site["user"]:
            return
        lines.append("    basic_auth {")
        lines.append(f"        {site['user']} {site['passwordHash']}")
        lines.append("    }")

    def _append_routing(self, lines: list[str], site: Mapping[str, Any]) -> None:
        needs_handles = bool(
            site["liveGateway"]
            or site["pathRoutes"]
            or site["allowedIps"]
            or site["deniedIps"]
        )
        if not needs_handles:
            self._append_main_route(lines, site, 1)
            return

        # IP 规则：named matcher 的 handle 保持书写顺序，排在所有路径 handle 之前。
        if site["deniedIps"]:
            lines.append("    @khc_denied remote_ip " + " ".join(site["deniedIps"]))
            lines.append("    handle @khc_denied {")
            lines.append("        abort")
            lines.append("    }")
        if site["allowedIps"]:
            lines.append("    @khc_not_allowed not remote_ip " + " ".join(site["allowedIps"]))
            lines.append("    handle @khc_not_allowed {")
            lines.append("        abort")
            lines.append("    }")
        if site["liveGateway"]:
            lines.append(f"    handle {LIVE_GATEWAY_PATH} {{")
            lines.append(f"        reverse_proxy {LIVE_GATEWAY_UPSTREAM}")
            lines.append("    }")
        for route in site["pathRoutes"]:
            lines.append(f"    handle {route['path']} {{")
            lines.append("        reverse_proxy " + " ".join(route["upstreams"]))
            lines.append("    }")
        lines.append("    handle {")
        self._append_main_route(lines, site, 2)
        lines.append("    }")

    def _append_main_route(self, lines: list[str], site: Mapping[str, Any], indent: int) -> None:
        prefix = "    " * indent
        if site["kind"] == "proxy":
            subdirectives: list[str] = []
            if len(site["upstreams"]) > 1:
                subdirectives.append(f"lb_policy {site['lbPolicy']}")
            if site["healthUri"]:
                subdirectives.append(f"health_uri {site['healthUri']}")
                subdirectives.append("health_interval 10s")
            if subdirectives:
                lines.append(prefix + "reverse_proxy " + " ".join(site["upstreams"]) + " {")
                for item in subdirectives:
                    lines.append(prefix + "    " + item)
                lines.append(prefix + "}")
            else:
                lines.append(prefix + "reverse_proxy " + " ".join(site["upstreams"]))
            return

        if site["kind"] == "static":
            lines.append(prefix + f"root * {site['root']}")
            try_files = list(site["tryFiles"])
            if not try_files and site["spa"]:
                try_files = ["{path}", f"/{site['index']}"]
            if try_files:
                lines.append(prefix + "try_files " + " ".join(try_files))
            file_server = "file_server" + (" browse" if site["browse"] else "")
            if site["index"] != DEFAULT_INDEX:
                lines.append(prefix + file_server + " {")
                lines.append(prefix + f"    index {site['index']}")
                lines.append(prefix + "}")
            else:
                lines.append(prefix + file_server)
            return

        lines.append(prefix + f"redir {site['redirectTo']} {int(site['redirectCode'])}")

    # ------------------------------------------------------------------
    # validate（在临时镜像目录里合并主 Caddyfile + 现有 imports 再校验）
    # ------------------------------------------------------------------
    def validate(self, ctx: Ctx, files: list[File]) -> None:
        for path in list(getattr(self._pending, "log_paths", []) or []):
            self._ensure_log_directory(path)
        snippet = getattr(self._pending, "snippet", None)
        cert_paths = list(getattr(self._pending, "certs", []) or [])
        if snippet is None:
            on_disk = read_text(self.snippet_path(ctx))
            if on_disk is None:
                return
            snippet = on_disk
        snippet = self._substitute_temp_paths(str(snippet), files, cert_paths)
        self._validate_config_tree(ctx, snippet)

    def _ensure_log_directory(self, path: str) -> None:
        """日志目录 0750；已存在则不改权限（避免破坏运维已设置的属主/权限）。"""

        parent = os.path.dirname(os.path.abspath(path))
        if parent in ("", "/"):
            raise ValidationFailed("日志路径不能直接位于文件系统根目录", details={"field": "log.path"})
        if os.path.isdir(parent):
            return
        try:
            os.makedirs(parent, mode=0o750, exist_ok=True)
            os.chmod(parent, 0o750)
        except OSError as exc:
            raise CommandFailed(
                f"无法创建日志目录 {parent}: {exc}",
                details={"path": parent},
            ) from exc

    def _ensure_log_dirs(self, ctx: Ctx, config: Any) -> None:
        if not isinstance(config, Mapping):
            return
        raw_sites = config.get("sites")
        if not isinstance(raw_sites, list):
            return
        for raw in raw_sites:
            if not isinstance(raw, Mapping):
                continue
            if not bool(raw.get("enabled", True)):
                continue
            log = raw.get("log")
            if not isinstance(log, Mapping) or not bool(log.get("enabled", False)):
                continue
            path = _text(log.get("path"))
            if path:
                self._ensure_log_directory(path)

    def _substitute_temp_paths(self, snippet: str, files: list[File], cert_paths: list[str]) -> str:
        """首次 apply 时证书还在临时文件上：把片段里的最终路径换成 tmp_path 再校验。"""

        wanted = {os.path.normpath(path) for path in cert_paths}
        mapping: dict[str, str] = {}
        for item in files:
            if not isinstance(item, File) or not item.tmp_path:
                continue
            final = os.path.normpath(str(item.path))
            if final in wanted or final.endswith((".crt", ".key")):
                mapping[final] = item.tmp_path
        for path in cert_paths:
            replacement = mapping.get(os.path.normpath(path))
            if replacement:
                snippet = snippet.replace(path, replacement)
        return snippet

    def _validate_config_tree(self, ctx: Ctx, snippet: str) -> None:
        caddyfile = ctx.paths.caddyfile
        self._validate_tree(ctx, _with_import(read_text(caddyfile)), {os.path.basename(self.snippet_path(ctx)): snippet})

    def _validate_tree(self, ctx: Ctx, caddyfile_text: str, snippets: Mapping[str, str]) -> None:
        caddyfile = ctx.paths.caddyfile
        caddy_dir = os.path.dirname(os.path.abspath(caddyfile))
        ensure_dir(caddy_dir)
        mirror: Optional[str] = None
        try:
            mirror = tempfile.mkdtemp(prefix=".khc-validate-")
            # 主 Caddyfile 里的相对 import（snippets/、khc.d/ 等）要在镜像目录里能解析：
            # 除 Caddyfile 与 khc.d 外的同目录项全部软链过去（证书等原始绝对路径也能访问）。
            for name in sorted(os.listdir(caddy_dir)):
                if name in ("Caddyfile", "khc.d") or name.startswith(".khc-validate-"):
                    continue
                target = os.path.join(mirror, name)
                if os.path.lexists(target):
                    continue
                try:
                    os.symlink(os.path.join(caddy_dir, name), target)
                except OSError:  # pragma: no cover - 少见的文件系统限制
                    pass

            _write_text(os.path.join(mirror, "Caddyfile"), _with_import(caddyfile_text), mode=0o644)
            mirror_khc = os.path.join(mirror, "khc.d")
            ensure_dir(mirror_khc, 0o755)
            real_khc = ctx.paths.caddy_dir
            if os.path.isdir(real_khc):
                for name in sorted(os.listdir(real_khc)):
                    if name in snippets:
                        continue
                    source = os.path.join(real_khc, name)
                    if not os.path.isfile(source):
                        continue
                    content = read_text(source)
                    if content is None:
                        continue
                    _write_text(os.path.join(mirror_khc, name), content, mode=0o644)
            for name, content in snippets.items():
                _write_text(os.path.join(mirror_khc, name), content, mode=0o644)

            result = ctx.run(
                [CADDY_BIN, "validate", "--config", os.path.join(mirror, "Caddyfile"), "--adapter", "caddyfile"],
                check=False,
            )
        finally:
            if mirror is not None:
                shutil.rmtree(mirror, ignore_errors=True)

        if result.rc == 0:
            return
        stderr = tail(result.stderr)
        stdout = tail(result.stdout)
        if result.rc == 127:
            raise ValidationFailed(
                "caddy 未安装或不可执行，无法校验站点配置（旧配置未改动）",
                details={"rc": 127, "stderr": stderr},
            )
        raise ValidationFailed(
            "caddy validate 未通过：配置有误（旧配置未改动，未 reload）",
            details={"rc": result.rc, "stderr": stderr, "stdout": stdout},
        )

    # ------------------------------------------------------------------
    # after_apply（内核钩子）：日志目录 + 证书内容变化时补一次 reload
    # ------------------------------------------------------------------
    def after_apply(
        self,
        ctx: Ctx,
        changes: list[dict[str, str]],
        config: Optional[Mapping[str, Any]] = None,
        previous: Optional[Mapping[str, Any]] = None,
    ) -> None:
        self._ensure_log_dirs(ctx, config)
        self._health_cache = None  # 配置变更后下一次 /state 重新探测
        changed_paths = {
            str(item.get("path"))
            for item in (changes or [])
            if isinstance(item, Mapping) and item.get("path")
        }
        if not changed_paths:
            return
        snippet_path = self.snippet_path(ctx)
        if snippet_path in changed_paths or ctx.paths.caddyfile in changed_paths:
            # 内核 _caddy_apply 已经 validate + reload（失败会抛错并回滚），这里只记录时间。
            self._record_reload(ctx, ok=True, source="kernel")
            return
        self._reload_caddy(ctx)

    def _reload_caddy(self, ctx: Ctx) -> None:
        result = ctx.run(
            [CADDY_BIN, "reload", "--config", ctx.paths.caddyfile, "--adapter", "caddyfile"],
            check=False,
        )
        if result.rc == 0:
            self._record_reload(ctx, ok=True, source="caddy")
            return
        fallback = ctx.systemctl("reload", CADDY_UNIT, check=False)
        if fallback.rc == 0:
            self._record_reload(ctx, ok=True, source="systemctl")
            return
        error = f"caddy reload rc={result.rc}: {tail(result.stderr, 500)}"
        self._record_reload(ctx, ok=False, source="caddy", error=error)
        raise CommandFailed(
            "caddy reload 失败（证书/配置变更未生效，内核将回滚）",
            details={
                "reloadRc": result.rc,
                "reloadStderr": tail(result.stderr),
                "systemctlRc": fallback.rc,
                "systemctlStderr": tail(fallback.stderr),
            },
        )

    def _record_reload(self, ctx: Ctx, *, ok: bool, source: str, error: Optional[str] = None) -> None:
        path = self.state_path(ctx)
        data = load_json(path, default={})
        if not isinstance(data, dict):
            data = {}
        data["lastReloadAt"] = iso_utc()
        data["lastReloadOk"] = bool(ok)
        data["lastReloadSource"] = source
        data["lastError"] = None if ok else (tail(str(error or ""), 500) or None)
        data["sites"] = count_site_blocks(read_text(self.snippet_path(ctx)))
        try:
            save_json(path, data, mode=0o600)
        except OSError as exc:  # pragma: no cover - 只在磁盘异常时发生
            LOG.warning("caddy-site: 写入 reload 状态失败: %s", exc)

    def _load_state(self, ctx: Ctx) -> dict[str, Any]:
        data = load_json(self.state_path(ctx), default={})
        return data if isinstance(data, dict) else {}

    def _applied_config(self, ctx: Ctx) -> Optional[dict[str, Any]]:
        """从内核 state.json 读取已生效配置（只读；用于健康探测）。"""

        data = load_json(ctx.paths.state_file, default={})
        if not isinstance(data, dict):
            return None
        apps = data.get("apps")
        if not isinstance(apps, dict):
            return None
        entry = apps.get(self.name)
        if not isinstance(entry, dict):
            return None
        config = entry.get("config")
        return config if isinstance(config, dict) else None

    def _mode_subnet(self, ctx: Ctx) -> Optional[ipaddress.IPv4Network]:
        """读取已生效的组网接口网段（用于判断站点上游是否在 VPN 内）。"""

        data = load_json(ctx.paths.state_file, default={})
        if not isinstance(data, Mapping):
            return None
        apps = data.get("apps")
        if not isinstance(apps, Mapping):
            return None
        entry = apps.get("wireguard")
        if not isinstance(entry, Mapping):
            return None
        config = entry.get("config")
        if not isinstance(config, Mapping):
            return None
        interface = config.get("interface")
        if not isinstance(interface, Mapping):
            return None
        try:
            network = ipaddress.ip_interface(_text(interface.get("address"))).network
        except ValueError:
            return None
        if network.version != 4:
            return None
        return network  # type: ignore[return-value]

    # ------------------------------------------------------------------
    # status（/state 使用；绝不能抛异常）
    # ------------------------------------------------------------------
    def status(self, ctx: Ctx) -> dict[str, Any]:
        try:
            result = self._status(ctx)
            result["problems"] = self._problems(result)
            return result
        except Exception as exc:  # noqa: BLE001 - 单个应用状态失败不能影响 /state
            LOG.warning("caddy-site status() failed: %s", exc)
            return {"error": str(exc)}

    def _problems(self, status: Mapping[str, Any]) -> list[dict[str, Any]]:
        """给核心诊断的通用问题列表（#49）：服务未运行、配置未生效、上游不可达。"""

        problems: list[dict[str, Any]] = []
        # 只有已经配置了站点时才把「服务未运行」当错误：节点上装了 Caddy 但
        # 还没发布任何站点时，服务不运行是正常状态，不应让诊断永久变红。
        sites_count = status.get("sites")
        has_sites = (
            isinstance(sites_count, int) and not isinstance(sites_count, bool) and sites_count > 0
        )
        if status.get("active") is False and has_sites:
            problems.append(
                {
                    "code": "inactive",
                    "severity": "error",
                    "title": "Caddy 服务未运行",
                    "hint": "caddy.service 未运行，所有站点不可访问。",
                    "action": {"id": "caddy.service", "label": "启动服务"},
                }
            )

        validate = status.get("validate")
        validate = validate if isinstance(validate, Mapping) else {}
        validate_ok = validate.get("ok")
        reload_ok = status.get("lastReloadOk")
        if validate_ok is False or reload_ok is False:
            if validate_ok is False:
                message = _text(validate.get("message")) or "caddy validate 未通过"
                hint = f"caddy validate 未通过：{message}（旧配置仍在运行）"
            else:
                hint = f"上次 reload 失败：{_text(status.get('lastError')) or 'reload 失败'}"
            hint = tail(hint, 300)
            problems.append(
                {
                    "code": "config_failed",
                    "severity": "error",
                    "title": "Caddy 配置未生效",
                    "hint": hint,
                    "evidence": {
                        "validateOk": validate_ok if isinstance(validate_ok, bool) else None,
                        "lastReloadOk": reload_ok if isinstance(reload_ok, bool) else None,
                    },
                }
            )

        sites = [site for site in (status.get("siteHealth") or []) if isinstance(site, Mapping)]
        down = [site for site in sites if _text(site.get("state")) == "down"]
        warned = [site for site in sites if _text(site.get("state")) == "warn"]

        def label(site: Mapping[str, Any]) -> str:
            return _text(site.get("name")) or _text(site.get("domain")) or "未命名"

        if down:
            names = "、".join(label(site) for site in down[:3])
            problems.append(
                {
                    "code": "upstream_down",
                    "severity": "error",
                    "title": f"{len(down)} 个站点上游不可达",
                    "hint": f"{names} 探测失败，请检查上游地址、端口与服务状态。",
                    "evidence": {"sites": len(sites), "down": len(down), "names": names},
                }
            )
        elif warned:
            names = "、".join(label(site) for site in warned[:3])
            problems.append(
                {
                    "code": "upstream_down",
                    "severity": "warn",
                    "title": f"{len(warned)} 个站点探测异常",
                    "hint": f"{names} 返回 4xx 或 TLS 校验失败（自签证书），请确认是否符合预期。",
                    "evidence": {"sites": len(sites), "warn": len(warned), "names": names},
                }
            )
        return problems

