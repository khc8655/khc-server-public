    def action_hash_password(self, ctx: Ctx, body: Mapping[str, Any]) -> dict[str, Any]:
        params = action_params(body)
        password = params.get("password")
        if password is None:
            raise ValidationFailed("缺少参数 password", details={"field": "password"})
        if not isinstance(password, str):
            raise ValidationFailed("password 必须是字符串", details={"field": "password"})
        if not password:
            raise ValidationFailed("password 不能为空", details={"field": "password"})
        if len(password) > 512:
            raise ValidationFailed("password 太长（>512）", details={"field": "password"})
        if any(char in password for char in ("\x00", "\r", "\n")):
            raise ValidationFailed("password 不允许包含换行或 NUL 字符", details={"field": "password"})
        # 密码走 stdin：不能出现在 argv（ps 可见）或内核命令日志里。
        result = ctx.run([CADDY_BIN, "hash-password"], input=password + "\n", check=False)
        if result.rc != 0:
            raise CommandFailed(
                "caddy hash-password 执行失败（hash-password 支持从 stdin 读取密码；请检查 caddy 版本/权限）",
                details={"rc": result.rc, "stderr": tail(result.stderr)},
            )
        hashed = _extract_bcrypt(result.stdout) or _extract_bcrypt(result.stderr)
        if not hashed:
            raise CommandFailed(
                "caddy hash-password 没有输出 bcrypt 哈希",
                details={"stdout": tail(result.stdout), "stderr": tail(result.stderr)},
            )
        return {
            "ok": True,
            "hash": hashed,
            "passwordHash": hashed,
            "result": {"hash": hashed, "algorithm": "bcrypt"},
            "cards": [{"title": "bcrypt 密码哈希", "value": hashed, "copy": True, "qr": False}],
        }

