    def _backup_paths(self, ctx: Ctx) -> list[str]:
        caddyfile = os.path.abspath(ctx.paths.caddyfile)
        directory = os.path.dirname(caddyfile)
        base = os.path.basename(caddyfile)
        if not os.path.isdir(directory):
            return []
        found: list[tuple[float, str]] = []
        try:
            names = os.listdir(directory)
        except OSError:
            return []
        for name in names:
            if not name.startswith(base + ".khc-backup-") or not BACKUP_NAME_RE.search(name):
                continue
            path = os.path.join(directory, name)
            try:
                found.append((os.path.getmtime(path), path))
            except OSError:
                continue
        found.sort(reverse=True)
        return [path for _, path in found]

    def _write_backup(self, ctx: Ctx, text: str) -> str:
        caddyfile = os.path.abspath(ctx.paths.caddyfile)
        base = os.path.basename(caddyfile)
        stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())
        candidate = os.path.join(os.path.dirname(caddyfile), f"{base}.khc-backup-{stamp}.bak")
        index = 2
        while os.path.exists(candidate):
            candidate = os.path.join(os.path.dirname(caddyfile), f"{base}.khc-backup-{stamp}-{index}.bak")
            index += 1
        atomic_write(candidate, text, mode=0o600)
        for stale in self._backup_paths(ctx)[BACKUP_KEEP:]:
            try:
                os.remove(stale)
            except OSError:  # pragma: no cover - 清理失败不影响接管
                LOG.warning("caddy: 无法清理旧备份 %s", stale)
        return candidate

    def _resolve_backup(self, ctx: Ctx, raw: Any) -> str:
        value = _text(raw).strip()
        if not value:
            raise BadRequest("缺少 backupPath", details={"field": "backupPath"})
        caddyfile = os.path.abspath(ctx.paths.caddyfile)
        path = os.path.abspath(value)
        if os.path.dirname(path) != os.path.dirname(caddyfile):
            raise BadRequest("备份路径必须位于 Caddyfile 同目录", details={"field": "backupPath"})
        base = os.path.basename(caddyfile)
        name = os.path.basename(path)
        if not name.startswith(base + ".khc-backup-") or not BACKUP_NAME_RE.search(name):
            raise BadRequest("不是本适配器生成的备份文件", details={"field": "backupPath"})
        if not os.path.isfile(path):
            raise BadRequest("备份文件不存在", details={"field": "backupPath"})
        return path

    def action_caddy_import_scan(self, ctx: Ctx, body: Mapping[str, Any]) -> dict[str, Any]:
        caddyfile = ctx.paths.caddyfile
        text = read_text(caddyfile)
        backups = [
            {
                "path": path,
                "name": os.path.basename(path),
                "updatedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(os.path.getmtime(path))),
            }
            for path in self._backup_paths(ctx)
        ]
        if text is None:
            return {
                "ok": True,
                "exists": False,
                "caddyfilePath": caddyfile,
                "caddyfileHash": None,
                "blocks": [],
                "imports": [],
                "backups": backups,
                "cards": [
                    {
                        "title": "Caddy 接管",
                        "value": "主 Caddyfile 不存在，没有可接管的站点",
                        "copy": False,
                        "qr": False,
                    }
                ],
            }

        parsed = parse_caddyfile(text)
        blocks: list[dict[str, Any]] = []
        for item in parsed["blocks"]:
            if item.get("kind") != "site":
                continue
            info = classify_site_block(str(item["text"]))
            blocks.append(
                {
                    "id": str(item["hash"])[:12],
                    "hash": item["hash"],
                    "address": item["header"],
                    "startLine": item["startLine"],
                    "endLine": item["endLine"],
                    "text": item["text"],
                    "supported": bool(info.get("supported")),
                    "reason": info.get("reason"),
                    "domains": info.get("domains") or [],
                    "listenPort": info.get("listenPort") or 443,
                    "kind": info.get("kind") or "proxy",
                    "upstreams": info.get("upstreams") or [],
                    "lbPolicy": info.get("lbPolicy") or DEFAULT_LB_POLICY,
                    "healthUri": info.get("healthUri") or "",
                    "root": info.get("root") or "",
                    "browse": bool(info.get("browse")),
                    "redirectTo": info.get("redirectTo") or "",
                    "redirectCode": info.get("redirectCode") or 302,
                    "tlsMode": info.get("tlsMode") or "auto",
                    "headers": info.get("headers") or {},
                    "compression": bool(info.get("compression")),
                    "logEnabled": bool(info.get("logEnabled")),
                    "logPath": info.get("logPath") or "",
                }
            )
        supported = sum(1 for block in blocks if block["supported"])
        return {
            "ok": True,
            "exists": True,
            "caddyfilePath": caddyfile,
            "caddyfileHash": hashlib.sha256(text.encode("utf-8")).hexdigest(),
            "blocks": blocks,
            "imports": parsed["imports"],
            "backups": backups,
            "cards": [
                {
                    "title": "Caddy 接管",
                    "value": f"{len(blocks)} 个外部站点块，其中 {supported} 个可自动接管",
                    "copy": False,
                    "qr": False,
                }
            ],
        }

    def action_caddy_import_preview(self, ctx: Ctx, body: Mapping[str, Any]) -> dict[str, Any]:
        """影子导入预览（只读）：展示将生成什么、会摘除什么、整树能否通过校验。"""

        digest = _text(action_params(body).get("hash")).strip()
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise BadRequest("hash 不合法（需要扫描结果里的完整块指纹）", details={"field": "hash"})
        text = read_text(ctx.paths.caddyfile)
        if text is None:
            raise BadRequest("主 Caddyfile 不存在，无法预览接管", details={"path": ctx.paths.caddyfile})
        parsed = parse_caddyfile(text)
        matches = [
            item for item in parsed["blocks"] if item.get("kind") == "site" and item.get("hash") == digest
        ]
        if not matches:
            raise BadRequest("目标站点块已变化，请重新扫描后再预览", details={"hash": digest})
        if len(matches) > 1:
            raise BadRequest("存在多个完全相同的站点块，无法确定要接管哪一个", details={"hash": digest})
        block = matches[0]
        info = classify_site_block(str(block["text"]))
        result: dict[str, Any] = {
            "ok": True,
            "hash": digest,
            "address": block["header"],
            "startLine": block["startLine"],
            "endLine": block["endLine"],
            "supported": bool(info.get("supported")),
            "reason": info.get("reason"),
            "caddyfileHash": hashlib.sha256(text.encode("utf-8")).hexdigest(),
            "site": None,
            "snippet": None,
            "remove": None,
            "import": None,
            "validate": None,
        }
        if not result["supported"]:
            return result
        try:
            draft = site_draft_from_block(info)
            normalized = self._normalize_sites({"sites": [draft]})
            rendered = self._render_block(normalized[0], self.certs_dir(ctx))
        except (BadRequest, KeyError, IndexError) as exc:
            result["supported"] = False
            result["reason"] = str(exc) or "无法把该站点块映射为面板站点"
            return result

        snippet = SNIPPET_HEADER + "\n" + rendered + "\n"
        new_text = _remove_caddyfile_block(text, block)
        proposed = _with_import(new_text)
        validate: dict[str, Any] = {"ok": False, "rc": None, "message": None}
        try:
            self._validate_tree(ctx, new_text, {os.path.basename(self.snippet_path(ctx)): snippet})
            validate = {"ok": True, "rc": 0, "message": None}
        except ValidationFailed as exc:
            details = dict(getattr(exc, "details", {}) or {})
            stderr = _text(details.get("stderr"))
            validate = {
                "ok": False,
                "rc": details.get("rc"),
                "message": str(exc) + (f"：{stderr}" if stderr else ""),
            }
        result.update(
            {
                "site": draft,
                "snippet": snippet,
                "remove": {
                    "startLine": block["startLine"],
                    "endLine": block["endLine"],
                    "text": block["text"],
                },
                "import": {
                    "line": "import khc.d/*",
                    "present": bool(IMPORT_RE.search(new_text)),
                    "willAppend": proposed != new_text,
                },
                "validate": validate,
            }
        )
        return result

    def action_caddy_import_takeover(self, ctx: Ctx, body: Mapping[str, Any]) -> dict[str, Any]:
        digest = _text(action_params(body).get("hash")).strip()
        if not re.fullmatch(r"[0-9a-f]{64}", digest):
            raise BadRequest("hash 不合法（需要扫描结果里的完整块指纹）", details={"field": "hash"})
        caddyfile = ctx.paths.caddyfile
        text = read_text(caddyfile)
        if text is None:
            raise BadRequest("主 Caddyfile 不存在，无法接管", details={"path": caddyfile})
        parsed = parse_caddyfile(text)
        matches = [
            item for item in parsed["blocks"] if item.get("kind") == "site" and item.get("hash") == digest
        ]
        if not matches:
            raise BadRequest("目标站点块已变化，请重新扫描后再接管", details={"hash": digest})
        if len(matches) > 1:
            raise BadRequest("存在多个完全相同的站点块，无法确定要接管哪一个", details={"hash": digest})
        block = matches[0]
        info = classify_site_block(str(block["text"]))
        if not info.get("supported"):
            raise ValidationFailed(
                "该站点块不支持自动接管：" + _text(info.get("reason")),
                details={"reason": info.get("reason")},
            )
        new_text = _remove_caddyfile_block(text, block)
        # 先校验摘除后的整棵配置树（不含新托管片段），失败则完全不落盘。
        self._validate_tree(ctx, new_text, {})
        backup = self._write_backup(ctx, text)
        atomic_write(caddyfile, new_text, mode=0o644)
        self._health_cache = None
        return {
            "ok": True,
            "hash": digest,
            "startLine": block["startLine"],
            "endLine": block["endLine"],
            "backupPath": backup,
            "caddyfilePath": caddyfile,
            # 已从主 Caddyfile 摘除，但尚未 reload；由面板随后保存并 apply 生效。
            "pending": True,
            "requiresApply": True,
            "cards": [
                {
                    "title": "Caddy 接管",
                    "value": f"已摘除 {_text(block['header'])}（备份 {os.path.basename(backup)}）",
                    "copy": False,
                    "qr": False,
                }
            ],
        }

    def action_caddy_import_restore(self, ctx: Ctx, body: Mapping[str, Any]) -> dict[str, Any]:
        backup = self._resolve_backup(ctx, action_params(body).get("backupPath"))
        content = read_text(backup)
        if content is None:
            raise BadRequest("备份文件不可读", details={"field": "backupPath"})
        self._validate_tree(ctx, content, {})
        atomic_write(ctx.paths.caddyfile, content, mode=0o644)
        self._health_cache = None
        self._reload_caddy(ctx)
        return {
            "ok": True,
            "restoredFrom": backup,
            "caddyfilePath": ctx.paths.caddyfile,
            "cards": [
                {
                    "title": "Caddy 接管",
                    "value": f"已从 {os.path.basename(backup)} 恢复主 Caddyfile",
                    "copy": False,
                    "qr": False,
                }
            ],
        }


