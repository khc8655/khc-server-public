def _site_upstreams(site: Mapping[str, Any]) -> list[str]:
    values: list[str] = []
    raw = site.get("upstreams")
    if isinstance(raw, (list, tuple)):
        values.extend(str(item) for item in raw if item)
    legacy = _text(site.get("upstream"))
    if legacy:
        values.append(legacy)
    for route in site.get("pathRoutes") or []:
        if isinstance(route, Mapping):
            values.extend(str(item) for item in (route.get("upstreams") or []) if item)
    return values


def _upstream_ip(value: str) -> Optional[ipaddress.IPv4Address]:
    """从 ``10.99.0.2:8080`` / ``http://10.99.0.2:8080`` 提取 IPv4。"""

    text = value.strip()
    text = re.sub(r"^[a-z][a-z0-9+.-]*://", "", text, flags=re.IGNORECASE)
    text = text.split("/")[0] or ""
    if text.startswith("["):
        return None
    host = text.split(":")[0] or ""
    try:
        address = ipaddress.ip_address(host)
    except ValueError:
        return None
    return address if address.version == 4 else None


def dependent_sites(
    sites: Iterable[Mapping[str, Any]],
    subnet: Optional[ipaddress.IPv4Network],
) -> list[str]:
    """启用站点中，上游落在组网网段内的站点名。"""

    if subnet is None:
        return []
    names: list[str] = []
    for site in sites:
        if bool(site.get("enabled", True)) is False:
            continue
        for upstream in _site_upstreams(site):
            address = _upstream_ip(upstream)
            if address is None or address not in subnet:
                continue
            name = _text(site.get("name")) or _text(site.get("domain")) or "未命名"
            if name not in names:
                names.append(name)
            break
    return names


def build_mode_impact(
    *,
    active: bool,
    sites: Iterable[Mapping[str, Any]],
    subnet: Optional[ipaddress.IPv4Network],
) -> list[dict[str, Any]]:
    """返回 ``status().modeImpact``：切到网关时 Caddy 必须在跑 + 依赖内网的站点。"""

    blockers: list[dict[str, Any]] = []
    if not active:
        blockers.append(
            {
                "code": MODE_CADDY_NOT_RUNNING,
                "message": "Caddy 未运行，切到网关前请先修复。",
                "fixPath": "sites",
            }
        )

    summary: list[str] = []
    names = dependent_sites(sites, subnet)
    if names:
        shown = "、".join(names[:3])
        if len(names) > 3:
            shown += " 等"
        summary.append(f"{len(names)} 个站点的上游在内网（{shown}），切换后不可用")

    return [{"target": "caddy", "blockers": blockers, "summary": summary}]


