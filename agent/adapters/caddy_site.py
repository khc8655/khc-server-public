    def cards(self, ctx: Ctx, config: Mapping[str, Any]) -> list[dict[str, Any]]:
        merged, errors = validate_config(self.schema, dict(config or {}) if isinstance(config, Mapping) else {})
        if errors:
            return []
        raw_sites = merged.get("sites") or []
        enabled = [site for site in raw_sites if isinstance(site, Mapping) and bool(site.get("enabled", True))]
        if not enabled:
            return [{"title": "站点", "value": "没有启用的站点", "copy": False, "qr": False}]
        addresses = []
        for site in enabled[:5]:
            domains = [str(item) for item in (site.get("domains") or []) if str(item).strip()]
            domain = domains[0] if domains else _text(site.get("domain"))
            port = site.get("listenPort", DEFAULT_LISTEN_PORT)
            if not domain:
                continue
            kind = _text(site.get("kind")) or "proxy"
            if kind == "redirect":
                addresses.append(f"{domain}:{port} → {_text(site.get('redirectTo'))}")
            elif kind == "static":
                addresses.append(f"{domain}:{port}（静态）")
            else:
                addresses.append(f"{domain}:{port}")
        value = f"{len(enabled)} 个站点已生效"
        if addresses:
            value += "：" + "、".join(addresses)
            if len(enabled) > len(addresses):
                value += " 等"
        return [{"title": "站点", "value": value, "copy": False, "qr": False}]

    def install(self, ctx: Ctx, config: Mapping[str, Any]) -> dict[str, Any]:
        version, installed = self._caddy_version(ctx)
        if not installed and ctx.paths.is_system:
            # P1：受控装包（白名单 caddy；自动识别 apt-get/dnf/yum/apk）。
            ensure_packages(ctx, ["caddy"])
            version, installed = self._caddy_version(ctx)
        if not installed:
            raise CommandFailed(
                "未检测到 caddy，请先安装（Debian/Ubuntu：apt-get install -y caddy）",
                details={"rc": 127},
            )
        return {
            "version": version or "unknown",
            "cards": [{"title": "Caddy", "value": version or "unknown", "copy": False, "qr": False}],
        }

    def uninstall(self, ctx: Ctx, purge: bool = False) -> dict[str, Any]:
        removed: list[str] = []
        certs_dir = self.certs_dir(ctx)
        if os.path.isdir(certs_dir):
            for name in sorted(os.listdir(certs_dir)):
                if not name.endswith((".crt", ".key")):
                    continue
                path = os.path.join(certs_dir, name)
                if os.path.isfile(path) and ctx.remove(path):
                    removed.append(path)
        if purge:
            shutil.rmtree(certs_dir, ignore_errors=True)
        else:
            try:
                os.rmdir(certs_dir)  # 只删空目录
            except OSError:
                pass
        state_removed = ctx.remove(self.state_path(ctx))
        ctx.log(f"caddy-site 已卸载（证书文件 {len(removed)} 个；Caddy 片段由内核清理）")
        return {
            "removed": removed,
            "stateRemoved": state_removed,
            "purged": bool(purge),
            "cards": [],
        }

