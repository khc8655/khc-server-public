    def action_caddy_reload(self, ctx: Ctx, body: Mapping[str, Any]) -> dict[str, Any]:
        caddyfile = ctx.paths.caddyfile
        if not os.path.isfile(caddyfile):
            raise ValidationFailed(
                "Caddyfile 不存在，无法 reload",
                details={"caddyfile": caddyfile},
            )
        check = ctx.run(
            [CADDY_BIN, "validate", "--config", caddyfile, "--adapter", "caddyfile"],
            check=False,
        )
        if check.rc != 0:
            raise ValidationFailed(
                "caddy validate 未通过，未执行 reload（配置文件未改动）",
                details={
                    "rc": check.rc,
                    "stderr": tail(check.stderr),
                    "stdout": tail(check.stdout),
                },
            )
        result = ctx.run(
            [CADDY_BIN, "reload", "--config", caddyfile, "--adapter", "caddyfile"],
            check=False,
        )
        source = "caddy"
        if result.rc != 0:
            fallback = ctx.systemctl("reload", CADDY_UNIT, check=False)
            if fallback.rc != 0:
                self._record_reload(
                    ctx,
                    ok=False,
                    source="caddy",
                    error=f"reload rc={result.rc}: {tail(result.stderr, 500)}",
                )
                raise CommandFailed(
                    "caddy reload 失败（配置文件未改动）",
                    details={
                        "reloadRc": result.rc,
                        "reloadStderr": tail(result.stderr),
                        "systemctlRc": fallback.rc,
                        "systemctlStderr": tail(fallback.stderr),
                    },
                )
            source = "systemctl"
        self._record_reload(ctx, ok=True, source=source)
        return {
            "ok": True,
            "reloaded": True,
            "source": source,
            "cards": [{"title": "Caddy", "value": f"已重载（{source}）", "copy": False, "qr": False}],
        }

