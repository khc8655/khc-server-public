    def _caddy_version(self, ctx: Ctx) -> tuple[Optional[str], bool]:
        result = ctx.run([CADDY_BIN, "version"], check=False)
        if result.rc != 0:
            return None, False
        output = (result.stdout or result.stderr or "").strip()
        if not output:
            return None, True
        token = output.splitlines()[0].split()[0]
        version = token[1:] if token.lower().startswith("v") else token
        return (version or None), True

    # -- 健康探测 -----------------------------------------------------------
    def _http_status(
        self,
        url: str,
        method: str,
        *,
        insecure: bool,
        timeout: float,
        headers: Optional[Mapping[str, str]] = None,
    ) -> int:
        context = ssl._create_unverified_context() if insecure else None  # noqa: SLF001 - 标准库接口
        request = urllib.request.Request(
            url,
            method=method,
            headers={"User-Agent": f"khc-agent/{VERSION}", **(headers or {})},
        )
        with urllib.request.urlopen(request, timeout=timeout, context=context) as response:  # noqa: S310
            return int(response.status)

    @staticmethod
    def _probe_error(exc: BaseException) -> str:
        return tail(str(exc), 200) or exc.__class__.__name__

    def _probe_url(
        self,
        url: str,
        timeout: float = HEALTH_TIMEOUT,
        headers: Optional[Mapping[str, str]] = None,
    ) -> dict[str, Any]:
        """HEAD -> GET 探测；TLS 证书校验失败（自签/internal）记为 warn。"""

        started = time.monotonic()

        def result(state: str, status: Optional[int] = None, error: Optional[str] = None) -> dict[str, Any]:
            return {
                "state": state,
                "status": status,
                "latencyMs": int((time.monotonic() - started) * 1000),
                "error": error,
            }

        try:
            status = self._http_status(url, "HEAD", insecure=False, timeout=timeout, headers=headers)
            if status < 400:
                return result("ok", status)
            return result("warn", status, f"HTTP {status}")
        except urllib.error.HTTPError as exc:
            if exc.code in (405, 501):  # 某些服务不支持 HEAD
                try:
                    status = self._http_status(url, "GET", insecure=False, timeout=timeout, headers=headers)
                    if status < 400:
                        return result("ok", status)
                    return result("warn", status, f"HTTP {status}")
                except urllib.error.HTTPError as exc2:
                    return result("warn", exc2.code, f"HTTP {exc2.code}")
                except Exception as exc2:  # noqa: BLE001
                    state = "warn" if _is_tls_verify_error(exc2) else "down"
                    return result(state, None, self._probe_error(exc2))
            return result("warn", exc.code, f"HTTP {exc.code}")
        except Exception as exc:  # noqa: BLE001
            if not _is_tls_verify_error(exc):
                return result("down", None, self._probe_error(exc))
            # 自签/internal 证书：退回不校验证书再试一次，能连通即 warn。
            try:
                status = self._http_status(url, "GET", insecure=True, timeout=timeout, headers=headers)
                return result("warn", status, "TLS 证书校验失败（自签/internal 证书）")
            except urllib.error.HTTPError as exc2:
                return result("warn", exc2.code, "TLS 证书校验失败（自签/internal 证书）")
            except Exception as exc2:  # noqa: BLE001
                return result("down", None, self._probe_error(exc2))

    def _site_health(self, config: Optional[Mapping[str, Any]]) -> list[dict[str, Any]]:
        entries: list[dict[str, Any]] = []
        if not isinstance(config, Mapping):
            return entries
        raw_sites = config.get("sites")
        if not isinstance(raw_sites, list):
            return entries
        now = time.monotonic()
        if self._health_cache is not None and (now - self._health_cache_at) < HEALTH_CACHE_TTL:
            return copy.deepcopy(self._health_cache)
        deadline = now + HEALTH_BUDGET
        for raw in raw_sites:
            if not isinstance(raw, Mapping):
                continue
            if not bool(raw.get("enabled", True)):
                continue
            try:
                entries.append(self._site_health_entry(raw, deadline))
            except Exception as exc:  # noqa: BLE001 - 健康探测绝不影响 /state
                entries.append(
                    {
                        "name": _text(raw.get("name")),
                        "domain": _text(raw.get("domain")),
                        "state": "unknown",
                        "status": None,
                        "latencyMs": None,
                        "error": self._probe_error(exc),
                        "upstreams": [],
                    }
                )
        self._health_cache = copy.deepcopy(entries)
        self._health_cache_at = time.monotonic()
        return entries

    def _site_health_entry(self, raw: Mapping[str, Any], deadline: float) -> dict[str, Any]:
        domains: list[str] = []
        raw_domains = raw.get("domains")
        if isinstance(raw_domains, list):
            domains = [_text(item) for item in raw_domains if _text(item)]
        if not domains:
            legacy = _text(raw.get("domain"))
            if legacy:
                domains = [legacy]
        domain = domains[0] if domains else ""
        name = _text(raw.get("name")) or domain
        kind = _text(raw.get("kind")) or "proxy"
        upstreams: list[str] = []
        if kind == "proxy":
            raw_upstreams = raw.get("upstreams")
            if isinstance(raw_upstreams, list):
                upstreams = [_text(item) for item in raw_upstreams if _text(item)]
            if not upstreams:
                legacy_upstream = _text(raw.get("upstream"))
                if legacy_upstream:
                    upstreams = [legacy_upstream]

        entry: dict[str, Any] = {
            "name": name,
            "domain": domain,
            "state": "unknown",
            "status": None,
            "latencyMs": None,
            "error": None,
            "upstreams": upstreams,
        }
        if not domain:
            entry["error"] = "缺少域名"
            return entry

        tls = raw.get("tls") if isinstance(raw.get("tls"), Mapping) else {}
        mode = _text(tls.get("mode")) or "auto"
        port = raw.get("listenPort", DEFAULT_LISTEN_PORT)
        if isinstance(port, bool) or not isinstance(port, int) or not 1 <= port <= 65535:
            port = DEFAULT_LISTEN_PORT
        scheme, default_port = ("http", 80) if mode == "off" else ("https", 443)
        # healthUri 既给 Caddy 主动健康检查，也决定状态探测路径（未配置时探根路径）。
        health_uri = _text(raw.get("healthUri"))
        probe_path = health_uri if health_uri.startswith("/") else "/"

        if time.monotonic() > deadline:
            entry["error"] = "探测超时预算用尽"
            return entry
        if scheme == "http":
            # TLS 关闭时站点按 Host 匹配明文监听；直接连本机回环并带 Host，
            # 避免域名解析/DNS 尚未就绪时把健康站点误报为 down。
            netloc = "127.0.0.1" if int(port) == default_port else f"127.0.0.1:{int(port)}"
            entry.update(self._probe_url(f"http://{netloc}{probe_path}", headers={"Host": domain}))
        else:
            netloc = domain if int(port) == default_port else f"{domain}:{int(port)}"
            entry.update(self._probe_url(f"https://{netloc}{probe_path}"))
        return entry

