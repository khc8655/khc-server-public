"""node_exporter 适配器（C1 演练用）。

完整覆盖：安装 -> 配置 -> 预览 diff -> 应用 -> 回滚 -> 卸载。

- name: node-exporter, version: 1.0.0, api: 1, requires_root: True
- 配置：``/etc/khc/apps/node-exporter/node_exporter.args``
- unit：``khc-node-exporter.service``（ExecStart=/opt/khc/apps/node-exporter/node_exporter）
- 端口：``config.port``（默认 9100）参与内核端口登记/冲突检查
- install：下载 GitHub release tar.gz（URL 可配）-> 可选 sha256 校验 -> 解压 ->
  ``--version`` 自检；不联网的单测通过注入 downloader/runner 完成。
"""

from __future__ import annotations

import os
import re
import shutil
import socket
import tarfile
from typing import Any, Mapping

from khc import Adapter, Ctx, File, Unit
from khc.util import (
    AdapterError,
    Conflict,
    CommandFailed,
    DownloadFailed,
    ValidationFailed,
    atomic_write,
    ensure_dir,
    read_text,
    tail,
)

APP_NAME = "node-exporter"
UNIT_NAME = "khc-node-exporter.service"
DEFAULT_PORT = 9100
DEFAULT_VERSION = "1.8.2"
DEFAULT_LISTEN = "0.0.0.0"

GITHUB_URL_TEMPLATE = (
    "https://github.com/prometheus/node_exporter/releases/download/"
    "v{version}/node_exporter-{version}.linux-{arch}.tar.gz"
)

_ARCH_MAP = {
    "x86_64": "amd64",
    "amd64": "amd64",
    "aarch64": "arm64",
    "arm64": "arm64",
    "armv7l": "armv7",
    "armv6l": "armv6",
    "i386": "386",
    "i686": "386",
    "ppc64le": "ppc64le",
    "s390x": "s390x",
}

_LISTEN_RE = re.compile(r"^[A-Za-z0-9._:\-\[\]]+$")
_VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:[-+][0-9A-Za-z.-]+)?$")
_EXTRA_ARG_RE = re.compile(r"^[^\s\"'\\]+$")
_LISTEN_ADDRESS_RE = re.compile(r"--web\.listen-address=([^\s\"]+)")


def detect_arch(machine: str | None = None) -> str:
    machine = (machine or os.uname().machine).lower()
    arch = _ARCH_MAP.get(machine)
    if arch is None:
        raise AdapterError(
            f"node_exporter 没有对应架构的预编译包: {machine}",
            details={"machine": machine, "supported": sorted(set(_ARCH_MAP.values()))},
        )
    return arch


class NodeExporter(Adapter):
    name = APP_NAME
    version = "1.0.0"
    api = 1
    requires_root = True
    description = "Prometheus node_exporter"
    ports = [("tcp", "port")]
    actions: Mapping[str, Any] = {}

    schema = {
        "type": "object",
        "properties": {
            "port": {
                "type": "integer",
                "default": DEFAULT_PORT,
                "minimum": 1,
                "maximum": 65535,
            },
            "version": {
                "type": "string",
                "default": DEFAULT_VERSION,
                "pattern": _VERSION_RE.pattern,
            },
            "listen": {
                "type": "string",
                "default": DEFAULT_LISTEN,
                "pattern": _LISTEN_RE.pattern,
            },
            "extraArgs": {
                "type": "array",
                "default": [],
                "maxItems": 64,
                "items": {"type": "string", "pattern": _EXTRA_ARG_RE.pattern},
            },
        },
        # 允许 downloadUrl / sha256 / arch / force 等安装期参数（不进配置界面）。
        "additionalProperties": True,
    }

    # ------------------------------------------------------------------
    # 路径
    # ------------------------------------------------------------------
    def args_path(self, ctx: Ctx) -> str:
        return os.path.join(ctx.paths.app_config_dir(self.name), "node_exporter.args")

    def binary_path(self, ctx: Ctx) -> str:
        return os.path.join(ctx.paths.app_opt_dir(self.name), "node_exporter")

    def unit_path(self, ctx: Ctx) -> str:
        return ctx.paths.unit_file(UNIT_NAME)

    # ------------------------------------------------------------------
    # render（纯函数：配置 -> 文件/unit）
    # ------------------------------------------------------------------
    def render(self, ctx: Ctx, config: Mapping[str, Any]) -> list[File | Unit]:
        port = int(config.get("port", DEFAULT_PORT))
        listen = str(config.get("listen", DEFAULT_LISTEN))
        extra_args = [str(arg) for arg in (config.get("extraArgs") or [])]

        if not _LISTEN_RE.match(listen):
            raise ValidationFailed(f"非法监听地址: {listen!r}", details={"field": "listen"})
        for arg in extra_args:
            if not _EXTRA_ARG_RE.match(arg):
                raise ValidationFailed(
                    f"extraArgs 包含非法字符: {arg!r}",
                    details={"field": "extraArgs", "value": arg},
                )

        args_path = self.args_path(ctx)
        binary_path = self.binary_path(ctx)
        flags = [f"--web.listen-address={listen}:{port}", *extra_args]
        args_content = (
            "# Generated by khc-agent (node-exporter adapter). Do not edit.\n"
            f'NODE_EXPORTER_ARGS="{" ".join(flags)}"\n'
        )

        unit_content = f"""# Generated by khc-agent (node-exporter adapter). Do not edit.
[Unit]
Description=khc node_exporter
Documentation=https://github.com/prometheus/node_exporter
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
EnvironmentFile={args_path}
ExecStart={binary_path} $NODE_EXPORTER_ARGS
Restart=on-failure
RestartSec=2
LimitNOFILE=65536
NoNewPrivileges=true

[Install]
WantedBy=multi-user.target
"""

        return [
            File(args_path, args_content, mode=0o644),
            Unit(UNIT_NAME, content=unit_content, restart=True, enable=True),
        ]

    # ------------------------------------------------------------------
    # validate（在临时文件上执行；不落盘）
    # ------------------------------------------------------------------
    def validate(self, ctx: Ctx, files: list[File]) -> None:
        binary = self.binary_path(ctx)
        if not os.path.isfile(binary):
            raise Conflict(
                "node_exporter 尚未安装，请先执行 install",
                details={"binary": binary, "app": self.name},
            )
        result = ctx.run([binary, "--version"], check=False)
        if result.rc != 0:
            raise CommandFailed(
                "node_exporter --version 自检失败",
                details={
                    "binary": binary,
                    "rc": result.rc,
                    "stderr": tail(result.stderr),
                    "stdout": tail(result.stdout),
                },
            )
        if "node_exporter" not in (result.stdout + result.stderr):
            raise CommandFailed(
                "node_exporter --version 输出异常",
                details={"output": tail(result.stdout + result.stderr)},
            )

    # ------------------------------------------------------------------
    # status（/state 使用；绝不能抛异常）
    # ------------------------------------------------------------------
    def status(self, ctx: Ctx) -> dict[str, Any]:
        binary = self.binary_path(ctx)
        args_path = self.args_path(ctx)
        installed = os.path.isfile(binary)
        running = ctx.unit_active(UNIT_NAME) if installed else False
        listen = None
        text = read_text(args_path) or ""
        match = _LISTEN_ADDRESS_RE.search(text)
        if match:
            listen = match.group(1)
        return {
            "installed": installed,
            "running": running,
            "listen": listen,
            "unit": UNIT_NAME,
            "binary": binary,
        }

    # ------------------------------------------------------------------
    # health（apply 后的健康检查）
    # ------------------------------------------------------------------
    def health(self, ctx: Ctx) -> bool:
        if ctx.unit_active(UNIT_NAME):
            return True
        # systemd 不可用/尚未就绪时，退化为直接探测本机端口。
        listen = None
        match = _LISTEN_ADDRESS_RE.search(read_text(self.args_path(ctx)) or "")
        if match:
            listen = match.group(1)
        if not listen:
            return False
        host, _, port_text = listen.rpartition(":")
        if not port_text.isdigit():
            return False
        probe_host = "127.0.0.1" if host in ("0.0.0.0", "", "::", "*") else host.strip("[]")
        try:
            with socket.create_connection((probe_host, int(port_text)), timeout=0.5):
                return True
        except OSError:
            return False

    # ------------------------------------------------------------------
    # install（任务内执行）
    # ------------------------------------------------------------------
    def install(self, ctx: Ctx, config: Mapping[str, Any]) -> dict[str, Any]:
        version = str(config.get("version") or DEFAULT_VERSION)
        if not _VERSION_RE.match(version):
            raise ValidationFailed(f"非法版本号: {version!r}", details={"field": "version"})
        arch = str(config.get("arch") or detect_arch())
        port = int(config.get("port", DEFAULT_PORT))
        listen = str(config.get("listen", DEFAULT_LISTEN))
        force = bool(config.get("force", False))

        binary = self.binary_path(ctx)
        app_dir = ctx.paths.app_opt_dir(self.name)
        ensure_dir(app_dir, 0o755)

        if os.path.isfile(binary) and not force:
            existing = ctx.run([binary, "--version"], check=False)
            output = existing.stdout + existing.stderr
            if existing.rc == 0 and version in output:
                ctx.log(f"已安装 node_exporter {version}，跳过下载（config.force=true 可强制重装）")
                return self._install_result(ctx, port, listen, version, skipped=True)

        url = self._resolve_url(config, version, arch)
        expected_sha = config.get("sha256") or os.environ.get("KHC_NODE_EXPORTER_SHA256")
        archive = os.path.join(app_dir, f"node_exporter-{version}.linux-{arch}.tar.gz")

        ctx.set_progress(5)
        ctx.log(f"下载 node_exporter {version} ({arch})")
        ctx.download(url, archive, sha256=str(expected_sha) if expected_sha else None, timeout=300)
        ctx.check_cancel()

        ctx.set_progress(45)
        ctx.log("解压 node_exporter")
        self._extract_binary(archive, binary)
        ctx.remove(archive)
        ctx.set_progress(70)

        ctx.log("运行 --version 自检")
        check = ctx.run([binary, "--version"], check=False)
        output = check.stdout + check.stderr
        if check.rc != 0:
            raise CommandFailed(
                "node_exporter --version 自检失败，安装未完成",
                details={"binary": binary, "rc": check.rc, "stderr": tail(check.stderr)},
            )
        if version not in output:
            raise CommandFailed(
                f"已安装的 node_exporter 版本与期望不一致（期望 {version}）",
                details={"binary": binary, "output": tail(output)},
            )

        ctx.set_progress(100)
        ctx.log(f"node_exporter {version} 安装完成")
        return self._install_result(ctx, port, listen, version, skipped=False)

    def _resolve_url(self, config: Mapping[str, Any], version: str, arch: str) -> str:
        direct = config.get("downloadUrl") or os.environ.get("KHC_NODE_EXPORTER_URL")
        if direct:
            return str(direct)
        template = os.environ.get("KHC_NODE_EXPORTER_URL_TEMPLATE")
        if template:
            try:
                return template.format(version=version, arch=arch)
            except (KeyError, IndexError) as exc:
                raise AdapterError(
                    f"KHC_NODE_EXPORTER_URL_TEMPLATE 格式错误: {exc}",
                    details={"template": template},
                ) from exc
        return GITHUB_URL_TEMPLATE.format(version=version, arch=arch)

    @staticmethod
    def _extract_binary(archive: str, binary: str) -> None:
        try:
            with tarfile.open(archive, "r:gz") as tar:
                member = None
                for candidate in tar.getmembers():
                    if candidate.isfile() and os.path.basename(candidate.name) == "node_exporter":
                        member = candidate
                        break
                if member is None:
                    raise AdapterError(
                        "下载的压缩包中找不到 node_exporter 可执行文件",
                        details={"archive": archive},
                    )
                if member.size > 200 * 1024 * 1024:
                    raise AdapterError("node_exporter 可执行文件异常巨大，拒绝解压")
                extracted = tar.extractfile(member)
                if extracted is None:
                    raise AdapterError("无法从压缩包读取 node_exporter")
                data = extracted.read()
        except tarfile.TarError as exc:
            raise AdapterError(
                f"压缩包损坏，无法解压: {exc}",
                details={"archive": archive},
            ) from exc
        ensure_dir(os.path.dirname(os.path.abspath(binary)))
        atomic_write(binary, data, mode=0o755)

    @staticmethod
    def _display_host(listen: str) -> str:
        return "127.0.0.1" if listen in ("0.0.0.0", "::", "*") else listen

    def _install_result(
        self,
        ctx: Ctx,
        port: int,
        listen: str,
        version: str,
        *,
        skipped: bool,
    ) -> dict[str, Any]:
        metrics_url = f"http://{self._display_host(listen)}:{port}/metrics"
        return {
            "cards": [
                {"title": "Metrics 地址", "value": metrics_url, "copy": True, "qr": False},
                {"title": "版本", "value": version, "copy": False, "qr": False},
            ],
            "version": version,
            "skipped": skipped,
            "binary": self.binary_path(ctx),
        }

    def cards(self, ctx: Ctx, config: Mapping[str, Any]) -> list[dict[str, Any]]:
        """apply 成功后返回通用结果卡片。"""

        port = int(config.get("port", DEFAULT_PORT))
        listen = str(config.get("listen", DEFAULT_LISTEN))
        return [
            {
                "title": "Metrics 地址",
                "value": f"http://{self._display_host(listen)}:{port}/metrics",
                "copy": True,
                "qr": False,
            }
        ]

    # ------------------------------------------------------------------
    # uninstall（任务内执行）
    # ------------------------------------------------------------------
    def uninstall(self, ctx: Ctx, purge: bool = False) -> dict[str, Any]:
        unit_removed = False
        ctx.unit_stop(UNIT_NAME, check=False)
        ctx.unit_disable(UNIT_NAME, check=False)
        if ctx.remove(self.unit_path(ctx)):
            unit_removed = True
        ctx.daemon_reload(check=False)

        purged = False
        if purge:
            shutil.rmtree(ctx.paths.app_opt_dir(self.name), ignore_errors=True)
            shutil.rmtree(ctx.paths.app_config_dir(self.name), ignore_errors=True)
            purged = True
            ctx.log("已清理程序与配置目录（purge=true）")

        ctx.log("node_exporter 已卸载")
        return {"purged": purged, "unitRemoved": unit_removed, "cards": []}


__all__ = ["NodeExporter", "UNIT_NAME", "detect_arch"]
